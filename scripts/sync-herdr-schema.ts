// Generates herdr's wire types from the schema the installed herdr
// binary reports, so devhub tracks the herdr actually running rather
// than a copy that drifts.
//
//   pnpm api:sync     re-read `herdr api schema --json` and regenerate
//   pnpm api:check    exit 1 if the installed herdr's schema differs
//
// HERDR_BIN_PATH (set inside herdr panes) or `herdr` on PATH is used.
//
// The schema's five sections each carry their own $defs, and names
// repeat across them without always matching (a request's ReadSource
// can differ from a response's), so each section becomes its own
// module instead of being merged.

import { execFileSync } from 'node:child_process';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'shared/src/herdr');
const genDir = join(outDir, 'generated');
const schemaPath = join(outDir, 'schema.json');

const SECTIONS: Record<string, string> = {
  request: 'Request',
  success_response: 'SuccessResponse',
  error_response: 'ErrorResponse',
  event: 'Event',
  subscription_event: 'SubscriptionEvent',
};

type Json = Record<string, any>;

function fail(message: string): never {
  console.error(`api:sync: ${message}`);
  process.exit(1);
}

function readSchema(): string {
  const bin = process.env.HERDR_BIN_PATH || 'herdr';
  try {
    const raw = execFileSync(bin, ['api', 'schema', '--json'], {
      encoding: 'utf8',
    });
    return JSON.stringify(JSON.parse(raw), null, 2) + '\n';
  } catch (error) {
    fail(
      `could not run \`${bin} api schema --json\`: ` +
        (error instanceof Error ? error.message : String(error)),
    );
  }
}

async function main() {
  const check = process.argv.includes('--check');
  const next = readSchema();
  const schema = JSON.parse(next) as Json;
  const current = await readFile(schemaPath, 'utf8').catch(
    () => null,
  );
  const prev = current ? (JSON.parse(current) as Json) : null;
  const label = `protocol ${schema.protocol} schema_version ${schema.schema_version}`;

  if (check) {
    if (current === next) {
      console.log(`api:sync: in sync (${label})`);
      return;
    }
    fail(
      `drift: vendored protocol ${prev?.protocol ?? 'none'}, ` +
        `installed herdr protocol ${schema.protocol} — run pnpm api:sync`,
    );
  }

  await rm(genDir, { recursive: true, force: true });
  await mkdir(genDir, { recursive: true });

  const banner =
    `/* Generated by scripts/sync-herdr-schema.ts from herdr ` +
    `${label}. Do not edit. */`;
  const index: string[] = [];

  for (const [section, title] of Object.entries(SECTIONS)) {
    if (!schema.schemas[section]) {
      fail(`schema has no "${section}" section`);
    }
    // $refs are rooted at the whole document; re-root them at the
    // section so it compiles standalone.
    const part = JSON.parse(
      JSON.stringify(schema.schemas[section]).replaceAll(
        `"#/schemas/${section}/`,
        '"#/',
      ),
    ) as Json;
    if (JSON.stringify(part).includes('"#/schemas/')) {
      fail(`section "${section}" references another section`);
    }
    const ts = await compile({ ...part, title }, title, {
      bannerComment: banner,
      additionalProperties: false,
      unreachableDefinitions: true,
      format: true,
      style: { singleQuote: true, printWidth: 70 },
    });
    const file = section.replace(/_/g, '-');
    await writeFile(join(genDir, `${file}.ts`), ts);
    index.push(`export type * as ${title} from './${file}.ts';`);
  }

  await writeFile(
    join(genDir, 'index.ts'),
    `${banner}\n\n${index.join('\n')}\n`,
  );
  await writeFile(schemaPath, next);

  const was = prev && prev.protocol !== schema.protocol;
  console.log(
    `api:sync: generated herdr types (${label})` +
      (was ? ` — protocol changed from ${prev.protocol}` : ''),
  );
}

main().catch((error: unknown) =>
  fail(error instanceof Error ? error.message : String(error)),
);
